import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import pandas as pd
import pytest

from src.dataset import (
    REQUIRED_LABELS,
    build_reproducible_subset,
    dataset_stats,
    load_config,
    load_raw,
    stratified_split,
)


@pytest.fixture(scope="module")
def config():
    return load_config("configs/config.yaml")


@pytest.fixture(scope="module")
def raw_df(config):
    return load_raw(config)


def test_raw_dataset_loads(raw_df):
    assert len(raw_df) > 0
    assert set(raw_df.columns) >= {"id", "text", "label", "text_hash"}


def test_label_mapping_is_exactly_trac1(raw_df):
    assert set(raw_df["label"].unique()) == set(REQUIRED_LABELS)


def test_no_duplicate_text_hashes(raw_df):
    assert raw_df["text_hash"].duplicated().sum() == 0


def test_subset_is_reproducible_with_same_seed(raw_df):
    subset_a = build_reproducible_subset(raw_df, size=500, seed=42)
    subset_b = build_reproducible_subset(raw_df, size=500, seed=42)
    assert list(subset_a["text_hash"]) == list(subset_b["text_hash"])


def test_subset_differs_with_different_seed(raw_df):
    subset_a = build_reproducible_subset(raw_df, size=500, seed=42)
    subset_c = build_reproducible_subset(raw_df, size=500, seed=7)
    assert list(subset_a["text_hash"]) != list(subset_c["text_hash"])


def test_subset_size_and_stratification(raw_df):
    subset = build_reproducible_subset(raw_df, size=1000, seed=42)
    assert len(subset) == 1000
    full_props = raw_df["label"].value_counts(normalize=True)
    sub_props = subset["label"].value_counts(normalize=True)
    for label in REQUIRED_LABELS:
        assert abs(full_props[label] - sub_props[label]) < 0.02


def test_stratified_split_ratios_and_disjointness(raw_df):
    subset = build_reproducible_subset(raw_df, size=1000, seed=42)
    split_config = {"train": 0.8, "validation": 0.1, "test": 0.1}
    train_df, val_df, test_df = stratified_split(subset, split_config, seed=42)

    assert len(train_df) + len(val_df) + len(test_df) == len(subset)
    assert abs(len(train_df) - 800) <= 2
    assert abs(len(val_df) - 100) <= 2
    assert abs(len(test_df) - 100) <= 2

    train_hashes = set(train_df["text_hash"])
    val_hashes = set(val_df["text_hash"])
    test_hashes = set(test_df["text_hash"])
    assert not (train_hashes & val_hashes)
    assert not (train_hashes & test_hashes)
    assert not (val_hashes & test_hashes)


def test_dataset_stats_shape(raw_df):
    stats = dataset_stats(raw_df)
    assert stats["total_rows"] == len(raw_df)
    assert set(stats["label_counts"].keys()) == set(REQUIRED_LABELS)


def test_prepared_splits_exist_on_disk():
    # These are generated by `python -m src.dataset --prepare`, which must
    # have been run at least once for this repo's Phase 1 state.
    for name in ["train", "validation", "test"]:
        path = os.path.join("data", "splits", f"{name}.csv")
        assert os.path.exists(path), f"{path} missing -- run `python -m src.dataset --prepare --size 4000`"
        df = pd.read_csv(path)
        assert set(df.columns) >= {"id", "text_hash", "original_text", "clean_text", "label"}
        assert set(df["label"].unique()).issubset(set(REQUIRED_LABELS))
