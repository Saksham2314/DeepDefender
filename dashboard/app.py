"""DeepDefender research dashboard (task section 16).

    streamlit run dashboard/app.py

Kept entirely separate from src/ (ML code) -- this file only reads already-
computed artifacts (data/, results/) and never trains or mutates anything.
Every section degrades to a clear "not available yet" message instead of
crashing when the underlying file doesn't exist, since most of these files
only appear after later pipeline phases (training, stacking, fairness,
robustness) have actually been run.
"""

import json
import os
import sys

import pandas as pd
import streamlit as st

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from src.dataset import load_config

st.set_page_config(page_title="DeepDefender Dashboard", layout="wide")

config = load_config("configs/config.yaml")
RESULTS_DIR = config["paths"]["results_dir"]
ARTIFACTS_DIR = config["paths"]["artifacts_dir"]
DATA_SPLITS_DIR = config["data"]["splits_dir"]
CLASSES = config["labels"]["classes"]


def missing(path: str) -> None:
    st.info(f"Not available yet -- expected at `{path}`. This is produced by a "
            "later pipeline phase; run the corresponding command and reload.")


def load_json(path: str):
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


st.title("DeepDefender Research Dashboard")
st.caption("Reads only already-computed results. Nothing here is generated by the dashboard itself.")

tab_dataset, tab_models, tab_stacking, tab_explain, tab_fairness, tab_robustness = st.tabs(
    ["Dataset", "Base Models", "Stacking", "Explainability", "Fairness", "Robustness"]
)

# --- Dataset tab -------------------------------------------------------
with tab_dataset:
    st.header("Dataset statistics")
    train_path = os.path.join(DATA_SPLITS_DIR, "train.csv")
    val_path = os.path.join(DATA_SPLITS_DIR, "validation.csv")
    test_path = os.path.join(DATA_SPLITS_DIR, "test.csv")

    if not all(os.path.exists(p) for p in [train_path, val_path, test_path]):
        missing(DATA_SPLITS_DIR + "/{train,validation,test}.csv")
    else:
        train_df = pd.read_csv(train_path)
        val_df = pd.read_csv(val_path)
        test_df = pd.read_csv(test_path)

        col1, col2, col3 = st.columns(3)
        col1.metric("Train rows", len(train_df))
        col2.metric("Validation rows", len(val_df))
        col3.metric("Test rows", len(test_df))

        st.subheader("Class distribution")
        dist_df = pd.DataFrame({
            "split": ["train"] * len(CLASSES) + ["validation"] * len(CLASSES) + ["test"] * len(CLASSES),
            "label": CLASSES * 3,
            "count": (
                [int((train_df["label"] == c).sum()) for c in CLASSES]
                + [int((val_df["label"] == c).sum()) for c in CLASSES]
                + [int((test_df["label"] == c).sum()) for c in CLASSES]
            ),
        })
        st.bar_chart(dist_df.pivot(index="label", columns="split", values="count"))

        with st.expander("Sample rows"):
            st.dataframe(train_df[["original_text", "clean_text", "label"]].head(20))

# --- Base models tab -----------------------------------------------------
with tab_models:
    st.header("Base model training status + metrics")
    base_models_dir = os.path.join(RESULTS_DIR, "base_models")
    model_keys = ["xlm_roberta", "indicbert", "mbert"]

    rows = []
    for key in model_keys:
        path = os.path.join(base_models_dir, f"{key}.json")
        data = load_json(path)
        final_dir = os.path.join(ARTIFACTS_DIR, "models", key, "final")
        trained = os.path.exists(final_dir)
        if data is None:
            rows.append({"model": key, "status": "trained (no results.json)" if trained else "not trained yet",
                         "test_accuracy": None, "test_f1_weighted": None, "test_f1_macro": None})
        else:
            test = data["test"]
            rows.append({
                "model": key, "status": "trained",
                "test_accuracy": test["accuracy"], "test_f1_weighted": test["f1_weighted"],
                "test_f1_macro": test["f1_macro"],
            })
    st.dataframe(pd.DataFrame(rows), use_container_width=True)

    st.subheader("Per-model detail")
    for key in model_keys:
        data = load_json(os.path.join(base_models_dir, f"{key}.json"))
        with st.expander(f"{key}"):
            if data is None:
                missing(os.path.join(base_models_dir, f"{key}.json"))
                continue
            st.write("Test metrics:", data["test"]["per_class"])
            st.write("Confusion matrix (rows=true, cols=predicted):", data["test"]["confusion_matrix"])
            fig_path = os.path.join(RESULTS_DIR, "figures", f"{key}_confusion_matrix.png")
            if os.path.exists(fig_path):
                st.image(fig_path)

# --- Stacking tab -----------------------------------------------------
with tab_stacking:
    st.header("Stacking ensemble")
    ensemble_path = os.path.join(RESULTS_DIR, "stacking", "ensemble_test_metrics.json")
    ensemble = load_json(ensemble_path)
    if ensemble is None:
        missing(ensemble_path)
    else:
        col1, col2, col3 = st.columns(3)
        col1.metric("Test accuracy", f"{ensemble['accuracy']:.3f}")
        col2.metric("Test F1 (weighted)", f"{ensemble['f1_weighted']:.3f}")
        col3.metric("Test F1 (macro)", f"{ensemble['f1_macro']:.3f}")
        st.write("Per-class:", ensemble["per_class"])
        st.write("Confusion matrix (rows=true, cols=predicted):", ensemble["confusion_matrix"])
        fig_path = os.path.join(RESULTS_DIR, "figures", "stacking_ensemble_confusion_matrix.png")
        if os.path.exists(fig_path):
            st.image(fig_path)

    st.subheader("Model comparison")
    comparison_path = os.path.join(RESULTS_DIR, "model_comparison.csv")
    if os.path.exists(comparison_path):
        st.dataframe(pd.read_csv(comparison_path), use_container_width=True)
    else:
        missing(comparison_path)

# --- Explainability tab ---------------------------------------------------
with tab_explain:
    st.header("Explanation preview")
    st.caption("Feature-attribution estimates only -- not a causal explanation (see docs/PAPER_BASELINE.md / src/explainability.py).")
    meta_path = os.path.join(ARTIFACTS_DIR, "stacking", "meta_classifier.joblib")
    if not os.path.exists(meta_path):
        missing(meta_path)
    else:
        sample_text = st.text_input("Try a sentence:", "tum bilkul pagal ho")
        if st.button("Explain"):
            with st.spinner("Running ensemble + occlusion attribution..."):
                from src.explainability import explain
                from src.stacking import StackingPredictor
                predictor = StackingPredictor()
                result = explain(predictor, sample_text, method="occlusion", top_k=5)
            st.write("Prediction:", result["prediction"])
            st.write("Top contributing words:", result["contributions"])
            st.caption(result["caveat"])

# --- Fairness tab -----------------------------------------------------
with tab_fairness:
    st.header("Fairness probe results")
    fairness_json_path = os.path.join(RESULTS_DIR, "fairness_report.json")
    report = load_json(fairness_json_path)
    if report is None:
        missing(fairness_json_path)
    else:
        st.warning(report["disclaimer"])
        st.metric("Templates with a label change across group terms",
                   f"{report['num_templates_with_label_changes_across_group_terms']}/{report['num_templates']}")
        for template_id, detail in report["templates"].items():
            with st.expander(f"{template_id}: {detail['template_text_example']}"):
                st.dataframe(pd.DataFrame(detail["per_group_term"]))

# --- Robustness tab -----------------------------------------------------
with tab_robustness:
    st.header("Robustness probe results")
    robustness_csv_path = os.path.join(RESULTS_DIR, "robustness_report.csv")
    if not os.path.exists(robustness_csv_path):
        missing(robustness_csv_path)
    else:
        df = pd.read_csv(robustness_csv_path)
        non_base = df[df["perturbation_type"] != "base"]
        match_rate = non_base.groupby("perturbation_type")["label_matches_base"].mean().sort_values()
        st.bar_chart(match_rate)
        st.caption("Label-match rate vs. the base sentence, per perturbation type (lower = label changed more often).")
        st.dataframe(df, use_container_width=True)
